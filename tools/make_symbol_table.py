"""Generates src/engine/SymbolTable.inc: the pages of the symbol keyboard (Ctrl+Alt+,).

    py -3 tools/make_symbol_table.py

Each page puts one symbol on each key of the keyboard, in this key order (46 keys):
    1234567890-=  qwertyuiop[]\\  asdfghjkl;'  zxcvbnm,./
A space means "no symbol on this key". The Bopomofo page is not listed here: the Composer maps
each Bopomofo key to its own symbol (standard layout).
"""
import os

KEYS = "1234567890-=qwertyuiop[]\\asdfghjkl;'zxcvbnm,./"
assert len(KEYS) == 46


def r(a, b):
    return ''.join(chr(c) for c in range(a, b + 1))


hiragana = r(0x3041, 0x3093)
katakana = r(0x30A1, 0x30F6)
greek_upper = ''.join(c for c in r(0x391, 0x3A9) if c not in '΢Ο')  # no gap, no Ο
greek_lower = ''.join(c for c in r(0x3B1, 0x3C9) if c not in 'ςο')  # no ς, no ο

PAGES = [
    ('標點', '，、。．‧；：？！…‥︰﹐﹑﹒﹔﹕﹖﹗｜–—―＿～＂＇｀＾＊＆＠＃％＄＼／·‘’“”〞‵′″'),
    ('括號', '（）［］｛｝〔〕【】《》〈〉「」『』〖〗〘〙︵︶︷︸︹︺︻︼︽︾︿﹀﹁﹂﹃﹄﹙﹚﹛﹜﹝﹞'),
    ('數學', '＋－×÷±＝≠≒≡≈＜＞≦≧∞√∫∮∑∏∂∴∵∠⊥∟⊿∩∪⊂⊃∈∋∀∃∅∇％‰°′″℃℉'),
    ('箭頭與圖形', '←↑→↓↖↗↘↙↔↕⇐⇒⇔○●◎◇◆□■△▲▽▼☆★◁▷◀▶♀♂♠♥♦♣♤♡♢♧※§¶†‡'),
    ('序號', '①②③④⑤⑥⑦⑧⑨⑩⑴⑵⑶⑷⑸⑹⑺⑻⑼⑽⒈⒉⒊⒋⒌⒍⒎⒏⒐⒑ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩⅰⅱⅲⅳⅴⅵ'),
    ('希臘字母', greek_upper + greek_lower),
    ('單位與貨幣', '＄￥￡￠€₩㎎㎏㎜㎝㎞㎡㏄㎖㎗㎘㏎㏑㏒㏕℡№℅™©®㏇㏘㍍㍑㍘㎥㎠㎢㎣㎤㎦㎧㎨㎩㎪㎫㎬㎭㎮'),
    ('框線', '─│┌┐└┘├┤┬┴┼═║╔╗╚╝╠╣╦╩╬╒╕╘╛╞╡╤╧╪▁▂▃▄▅▆▇█▏▎▍▌▋▊▉'),
    ('平假名（一）', hiragana[:46]),
    ('平假名（二）', hiragana[46:]),
    ('片假名（一）', katakana[:46]),
    ('片假名（二）', katakana[46:]),
]


def main():
    lines = ['// Generated by tools/make_symbol_table.py. Do not edit by hand.',
             '// { title, symbols in key order "' + KEYS.replace('\\', '\\\\') + '" (space = none) }']
    for title, symbols in PAGES:
        assert len(symbols) <= 46, (title, len(symbols))
        assert all(ord(c) < 0x10000 for c in symbols), title
        assert len(set(symbols)) == len(symbols), (title, [c for c in symbols if symbols.count(c) > 1])
        padded = symbols.ljust(46)
        # \x escapes are greedy in C++: split the literal after each one.
        parts = []
        for c in padded:
            parts.append('L"\\x%04X"' % ord(c) if ord(c) > 0x7E or c in '\\"' else 'L"%s"' % c)
        lines.append('{L"%s", %s},' % (''.join('\\x%04X' % ord(c) for c in title), ' '.join(parts)))
    out = os.path.join(os.path.dirname(__file__), '..', 'src', 'engine', 'SymbolTable.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', len(PAGES), 'pages to', os.path.normpath(out))


if __name__ == '__main__':
    main()
